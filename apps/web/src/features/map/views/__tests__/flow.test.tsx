import { act, renderHook, waitFor } from '@testing-library/react';
import { afterEach, expect, it, vi } from 'vitest';
import { api } from '../../../../lib/api.js';
import { typeColor, useFlowEdges, usePulseClock } from '../flow.js';
import { graph, payload } from './fixtures.js';
vi.mock('../../../../lib/api.js', () => ({ api: { getGraphEdges: vi.fn() } }));
afterEach(() => { vi.restoreAllMocks(); vi.unstubAllGlobals(); });
it('filters both endpoints, ignores stale graph responses, and stops on unmount', async () => {
  let resolve!: (value: typeof graph) => void;
  vi.mocked(api.getGraphEdges).mockImplementationOnce(() => new Promise((done) => { resolve = done; }));
  const p = payload();
  const hook = renderHook(({ p }) => useFlowEdges(p), { initialProps: { p } });
  vi.mocked(api.getGraphEdges).mockResolvedValueOnce({ ...graph, edges: [...graph.edges, { ...graph.edges[0]!, targetId: 'outside' }] });
  hook.rerender({ p: payload() });
  await waitFor(() => expect(hook.result.current.edges).toHaveLength(2));
  await act(async () => resolve({ ...graph, edges: [] }));
  expect(hook.result.current.edges).toHaveLength(2);
  vi.mocked(api.getGraphEdges).mockImplementationOnce(() => new Promise((done) => { resolve = done; }));
  hook.rerender({ p: payload() }); hook.unmount();
  await act(async () => resolve(graph));
  expect(typeColor('semantic')).toBe('var(--sem)'); expect(typeColor('episodic')).toBe('var(--epi)'); expect(typeColor('procedural')).toBe('var(--pro)');
});
it('pauses the presentation clock while hidden, resumes without jumping, and cleans up', () => {
  const queue = new Map<number, FrameRequestCallback>(); let next = 0, hidden = false;
  vi.stubGlobal('requestAnimationFrame', (callback: FrameRequestCallback) => { queue.set(++next, callback); return next; });
  vi.stubGlobal('cancelAnimationFrame', (id: number) => queue.delete(id));
  vi.spyOn(document, 'hidden', 'get').mockImplementation(() => hidden);
  const tick = (time: number) => act(() => { const pending = [...queue.values()]; queue.clear(); pending.forEach((cb) => cb(time)); });
  const hook = renderHook(({ reduced, key }) => usePulseClock(key, reduced, 1000), { initialProps: { reduced: false, key: 1 } });
  tick(100); tick(300); expect(hook.result.current).toBe(200);
  act(() => { hidden = true; document.dispatchEvent(new Event('visibilitychange')); }); expect(queue.size).toBe(0);
  act(() => { hidden = false; document.dispatchEvent(new Event('visibilitychange')); });
  tick(2000); expect(hook.result.current).toBe(200); tick(2300); expect(hook.result.current).toBe(500);
  tick(3000); expect(hook.result.current).toBe(1000); expect(queue.size).toBe(0);
  hook.rerender({ reduced: false, key: 2 }); expect(hook.result.current).toBe(0); expect(queue.size).toBe(1);
  hook.rerender({ reduced: true, key: 2 }); expect(hook.result.current).toBe(1000); expect(queue.size).toBe(0);
  hook.rerender({ reduced: false, key: 0 }); expect(queue.size).toBe(0);
  hook.unmount();
});
